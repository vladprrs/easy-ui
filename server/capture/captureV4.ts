/**
 * Общий kill-switch capture-группы волны снятия блокеров (план
 * `docs/plans/2026-08-08-blocker-removal-eui-br.md` §2 и §4): **EUI-BR-02** (per-side paint padding,
 * capability `paintCapturePaddingV1`) и **EUI-BR-04** (exact content-hug canvas, capability
 * `exactContentHugCanvasV1`).
 *
 * Один тумблер на две фичи — решение §13 плана (C6, «7 kill-switch'ей вместо 11»): обе живут в
 * одной зоне (кадр капчура ↔ канва сравнения) и включаются одним окном пересъёмки/re-diff'а, а два
 * независимых тумблера дали бы состояние «кадр снят с новым полем, а канва сведена по-старому»,
 * которого ни один тест не описывает.
 *
 * `EASYUI_CAPTURE_V4_DISABLED=1` — **legacy byte-for-byte**: манифест с `paintPaddingPx` отвергается
 * типизированным `422 capture_padding_disabled`, кадр снимается скалярным полем, канва сравнения
 * судится прежним `maxDimensionDeltaPx`, `rawDiffPctOfSurface` не считается вовсе, а проверки
 * масштаба эталона не существует.
 *
 * Значение читается **на каждом вызове**, а не один раз на процесс (в отличие от
 * `resourceBarrier.ts`): в отпечатки политика этой волны входит не значениями readiness-политики, а
 * условным `comparisonPolicyVersion` слоя сравнения — то есть переключение стоит re-diff'а, а не
 * рассинхрона трёх хэшей внутри одного рана. Это же делает тумблер проверяемым парными тестами
 * «фича / legacy» без перезапуска процесса.
 */

/** Активна ли capture-группа волны (BR-02 + BR-04). */
export const captureV4Enabled = (): boolean => process.env.EASYUI_CAPTURE_V4_DISABLED !== "1";

/**
 * Версия политики **сравнения** волны (BR-04). Входит в `comparisonFingerprint` условным спредом
 * ровно тогда, когда группа активна, и это единственный механизм инвалидации: смысл кода изменился
 * (точная канва, процент по поверхности сравнения, проверка масштаба эталона), а ни одно поле
 * манифеста при этом не поменялось, поэтому сохранённые под старой семантикой результаты обязаны
 * перестать переиспользоваться (ревью B2 раунда 2). `CASE_FINGERPRINT_ALGO_VERSION` при этом
 * **не** двигается: bump ALGO инвалидировал бы reuse всего корпуса, включая случаи, которых волна
 * не касается, а условный спред двигает ровно те кейсы, которые сравниваются по новым правилам.
 */
export const COMPARISON_POLICY_VERSION = 2;

/** Бюджет площади одного кадра, Мпикс: `(w+left+right) × (h+top+bottom) × dsf²` (BR-02). */
export const CAPTURE_FRAME_BUDGET_MPX = 20;
