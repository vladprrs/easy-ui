/**
 * **Политика прода.** Выбрана калибровкой T0 на прод-дампе (115 активных публикаций
 * yandex-pay, 6555 пар, снят 2026-07-31) перебором всех 11 628 наборов весов с шагом 0.05;
 * отчёт с семью замерами — `docs/audit/2026-07-31-matcher-calibration.md`, воспроизводится
 * командой из его шапки поверх этих же модулей.
 *
 * Почему так, а не по спеке:
 * - **source 0.75.** Единственный сигнал, разводящий копипасту и легитимного соседа по
 *   каталогу: `sourceShingles` нормализует локальные имена и литералы, поэтому переименование
 *   его не сбивает, а «фирменный стиль» дизайн-системы даёт не больше 0.67 (замеренный потолок
 *   легитимных пар — `yp-app-home-more-important ↔ yp-app-home-vitrina`).
 * - **0.05 на остальных сигналах.** Не ноль: сигнал с нулевым весом мёртв, а перенормировка
 *   неприменимых сигналов (§3.2) делает эти веса значимыми там, где исходника нет — при поиске
 *   кандидатов по одному `intent` применимы только имя и описание, и они получают равные доли.
 * - **blocking 0.70.** Потолок легитимных пар 0.6662 плюс запас 0.03 (замер 4: в полосе ±0.03
 *   вокруг порога нет ни одной пары каталога). Худшая из 345 обязательных копий набирает
 *   0.7023, то есть порог лежит внутри измеренного зазора 0.036.
 * - **review 0.53.** Ширина полосы 0.17 — из спеки §3; на прод-каталоге в неё попадают 8 пар
 *   из 6555, то есть выдача кандидатов не зашумляется.
 *
 * Граница честности (отчёт, замеры 3 и 7): копипаста с правкой props и дописанным кодом ловится
 * в 76% случаев, а «ролевые» дубликаты аудита 2026-07-20 — 1 из 9. Ролевые закрывает бэкфилл
 * `canonicalFor` в проекте 3, а не смена весов: ни один из 11 628 наборов не разводит их с
 * легитимными парами. Смена любого числа здесь — версионное изменение: `policyVersion` растёт,
 * отчёт перегенерируется, тесты обновляются (план §5.5).
 */
export const CALIBRATED_POLICY: MatchPolicy = {
  policyVersion: 1,
  weights: { props: 0.05, io: 0.05, source: 0.75, name: 0.05, description: 0.05, levelScope: 0.05 },
  blockingThreshold: 0.7,
  reviewThreshold: 0.53,
};

/**
 * **Пороги композиционных мэтчей** (план 2026-08-03 W9). Веса те же, что у прода: слот сигнала
 * «тело» у композиции занимает структура (`compositionSignature.ts`), поэтому смысл весов не
 * меняется. Отличаются только пороги, и они **консервативнее** калиброванных:
 *
 * - калибровка T0 мерила распределение score на парах **компонентов**; на композициях такого
 *   замера нет, и переносить 0.70 было бы выдачей неизмеренного за измеренное;
 * - в W9 композиционный вердикт **рекомендательный** (409 не выдаётся вовсе), но он печатается
 *   агенту как «уже есть — переиспользуй», поэтому ложная блокировка дороже ложного пропуска:
 *   агент бросит правильную работу, а пропущенный дубль всплывёт на ревью;
 * - точный структурный дубль ловится **отпечатком без порога** (`structuralMatch`), то есть
 *   главный случай W9 от значения `blockingThreshold` не зависит.
 *
 * `policyVersion` тот же, что у прод-политики: это её пороговая ветка для другого типа
 * артефакта, а не новое поколение весов. Смена любого числа здесь — версионное изменение.
 */
export const COMPOSITION_MATCH_POLICY: MatchPolicy = {
  policyVersion: 1,
  weights: CALIBRATED_POLICY.weights,
  blockingThreshold: 0.85,
  reviewThreshold: 0.6,
};

/** Сумма весов стартовой политики равна 1.0; перенормировка матчера от этого не зависит. */
export const totalWeight = (weights: MatchWeights): number =>
  weights.props + weights.io + weights.source + weights.name + weights.description + weights.levelScope;
